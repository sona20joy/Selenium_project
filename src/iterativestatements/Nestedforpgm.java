package iterativestatements;

public class Nestedforpgm {

	public static void main(String[] args) {
		for(int i=1;i<=3;i++)
		{
		for(int j=1;j<=4;j++)
			{
			System.out.print("*");
			} // return back to j++ because the condition is true. when the condition become false then back to outerloop i++
		System.out.println();
	} // return back to outerloop i++
		
		
		// ****
		// ****
		// **** 
		// 3 rows and 4 columns
		// 3 by 4 matrix

	}

}
