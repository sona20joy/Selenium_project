package javapackage;

public class Datatypepgm {

	public static void main(String[] args) {
		 byte  byteNumber=10;
		 System.out.println("The value of byteNumber="+byteNumber);
		 
		 short shortNumber = 20;
		 System.out.println("The value of byteNumber="+shortNumber);
		 
		 int intNumber=50;
		 System.out.println("The value of intNumber="+intNumber);
		 
		 long longNumber=5089000012L;
		 System.out.println("The value of longNumber="+longNumber);
		 
		 float floatNumber=3.14F;
		 System.out.println("The value of floatNumber="+floatNumber);
		 
		 double doubleNumber=8.9768;
		 System.out.println("The value of doubleNumber="+doubleNumber);	
		 
		 boolean result =5>3;
		 System.out.println("The value of result="+result);	
		 
		 char characterValue = 'H';
		 System.out.println("The value of charValue="+characterValue);
		 
		 char symbol ='&';
		 System.out.println("The value of symbol="+symbol);
		 
		 String name ="sona";  //string value should be enclosed within double quotes,
		                       // S should be in Caps as string is a class
		 System.out.println("The value of name ="+name);
		 
				 
		 


	}

}
